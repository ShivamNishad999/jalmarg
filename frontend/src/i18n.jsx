const LangContext = createContext({ lang: 'en', setLang: () => {}, t: (k) => k })

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try {
      return localStorage.getItem('jalmarg-lang') || (navigator.language?.startsWith('hi') ? 'hi' : 'en')
    } catch {
      return 'en'
    }
  })
  useEffect(() => {
    try { localStorage.setItem('jalmarg-lang', lang) } catch { /* private mode */ }
    document.documentElement.lang = lang
  }, [lang])
  const t = (key) => STRINGS[lang][key] ?? STRINGS.en[key] ?? key
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}

export const useLang = () => useContext(LangContext)

/** Turns an ApiError (or anything thrown) into a message in the current language. */
export function errorText(e, t) {
  if (!e) return ''
  if (e.code && STRINGS.en['e_' + e.code]) return t('e_' + e.code)
  if (e.kind && e.kind !== 'HTTP' && STRINGS.en['e_' + e.kind]) return t('e_' + e.kind)
  return e.message || t('error')
}
