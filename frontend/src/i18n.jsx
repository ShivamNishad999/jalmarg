const LangContext = createContext({ lang: 'en', setLang: () => {}, t: (k, vars) => k })

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try {
      const stored = localStorage.getItem('jalmarg-lang')
      return ['en', 'hi'].includes(stored) ? stored : (navigator.language?.startsWith('hi') ? 'hi' : 'en')
    } catch {
      return 'en'
    }
  })

  useEffect(() => {
    try { localStorage.setItem('jalmarg-lang', lang) } catch { /* private mode */ }
    document.documentElement.lang = lang
  }, [lang])

  const t = useCallback((key, vars = {}) => {
    let str = stage2Strings[lang]?.[key] ?? STRINGS[lang]?.[key] ?? STRINGS.en?.[key] ?? key
    if (vars && typeof vars === 'object') {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), () => String(v))
      })
    }
    return str
  }, [lang])

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}

export const useLang = () => useContext(LangContext)
